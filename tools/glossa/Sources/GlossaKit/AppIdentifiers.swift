import Foundation

/// Τα αναγνωριστικά που πρέπει να συμφωνούν ανάμεσα στην εφαρμογή iOS και το
/// πληκτρολόγιο. Αν αλλάξεις κάποιο, άλλαξέ το ΚΑΙ στα entitlements και στο
/// ios/project.yml — αλλιώς οι δύο διεργασίες παύουν σιωπηλά να βλέπουν τις
/// ίδιες ρυθμίσεις.
enum AppIdentifiers {
    static let appGroup = "group.gr.a2l.glossa"

    /// Τα κλειδιά μοιράζονται μέσω του entitlement `keychain-access-groups`,
    /// που είναι ίδιο και στους δύο στόχους. Όταν το group της καταχώρισης δεν
    /// δηλώνεται ρητά, το iOS χρησιμοποιεί το ΠΡΩΤΟ της λίστας — άρα αρκεί να
    /// υπάρχει ένα, το ίδιο, και στα δύο. Γι' αυτό δεν ορίζεται εδώ τίποτα:
    /// θα χρειαζόταν το πρόθεμα της ομάδας ανάπτυξης, που είναι γνωστό μόνο
    /// κατά τη μεταγλώττιση.
    static let keychainAccessGroup: String? = nil
}
